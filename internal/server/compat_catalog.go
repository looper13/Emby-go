func (a *App) users(c *gin.Context) {
	users := []gin.H{}
	if !strings.EqualFold(c.Query("IsHidden"), "true") && !strings.EqualFold(c.Query("IsDisabled"), "true") && !strings.EqualFold(c.Query("IsGuest"), "true") {
		all, _ := a.db.Users()
		current, _ := a.db.User(a.db.UserID())
		for _, user := range all {
			if !user.Disabled && (current.Administrator || current.ID == user.ID) {
				users = append(users, (&App{appState: a.appState, db: a.db.ForUser(user.ID)}).userDto())
			}
		}
	}
	c.JSON(http.StatusOK, users)
}

func (a *App) virtualFolders(c *gin.Context) {
	folders, err := a.virtualFolderItems()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	c.JSON(http.StatusOK, folders)
}

func (a *App) virtualFoldersQuery(c *gin.Context) {
	folders, err := a.virtualFolderItems()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	start, _ := strconv.Atoi(c.DefaultQuery("StartIndex", "0"))
	if start < 0 {
		start = 0
	}
	total := len(folders)
	limit, err := strconv.Atoi(c.DefaultQuery("Limit", strconv.Itoa(total)))
	if err != nil || limit < 0 {
		limit = total
	}
	pageStart := min(start, total)
	pageEnd := pageStart + min(limit, total-pageStart)
	c.JSON(http.StatusOK, gin.H{"Items": folders[pageStart:pageEnd], "TotalRecordCount": total, "StartIndex": start})
}

func (a *App) virtualFolderItems() ([]gin.H, error) {
	libraries, err := a.db.UserLibraries()
	if err != nil {
		return nil, err
	}
	folders := make([]gin.H, 0, len(libraries))
	cfg := a.configSnapshot()
	for _, library := range libraries {
		id := externalLibraryID(library.ID)
		if !library.IsDirectory() {
			folders = append(folders, gin.H{"Name": library.Name, "Locations": []string{}, "ItemId": id, "Id": id, "LibraryOptions": gin.H{"PathInfos": []gin.H{}, "EnableRealtimeMonitor": false}})
			continue
		}
		folders = append(folders, gin.H{
			"Name": library.Name, "Locations": []string{library.Path},
			"CollectionType": library.CollectionType(), "ItemId": id, "Id": id,
			"LibraryOptions": gin.H{
				"ContentType": library.CollectionType(), "PathInfos": []gin.H{{"Path": library.Path}},
				"EnableRealtimeMonitor":        !cfg.DisableLibraryMonitor && cfg.MonitorMode() == librarywatch.ModeRealtime,
				"EnableChapterImageExtraction": false, "ExtractChapterImagesDuringLibraryScan": false,
			},
		})
	}
	return folders, nil
}

// ThumbnailSet describes timeline preview frames, not poster/backdrop images.
// No preview frames are generated by this server, so available items have an
// empty set. Checking existence keeps unknown and hidden item IDs as 404.
func (a *App) thumbnailSet(c *gin.Context) {
	if strings.HasPrefix(c.Param("id"), "anime-") {
		if _, err := a.resolveUserMedia(c.Param("id")); err != nil {
			c.Status(404)
			return
		}
		c.JSON(200, gin.H{"AspectRatio": 0.0, "Thumbnails": []gin.H{}})
		return
	}
	id, err := strconv.ParseInt(c.Param("id"), 10, 64)
	part := 0
	if err != nil {
		var ok bool
		id, part, ok = parseVirtualPartID(c.Param("id"))
		if !ok {
			c.JSON(http.StatusNotFound, gin.H{"error": "not found"})
			return
		}
	}
	movie, err := a.db.Movie(id)
	if err != nil || !movie.IsVisible() || (part > 0 && part-2 >= len(movie.AdditionalParts)) {
		c.JSON(http.StatusNotFound, gin.H{"error": "not found"})
		return
	}
	c.JSON(http.StatusOK, gin.H{"AspectRatio": 0.0, "Thumbnails": []gin.H{}})
}

